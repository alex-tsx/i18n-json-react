const {readFile, readdir, lstat, mkdir, writeFile, rename, unlink} = require('node:fs/promises');
const {randomUUID} = require('node:crypto');
const path = require('node:path');
const {parseFeature, resolveRoot} = require('../../bundlers/shared.cjs');

const HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by i18n-json-react Android resources. Do not edit. -->\n';
const RESOURCE_NAME = /^[a-z][a-z0-9_]*$/;
const record = value => value !== null && typeof value === 'object' && !Array.isArray(value);
const own = (object, key) => Object.prototype.hasOwnProperty.call(object, key);

function fields(value, allowed, context) {
  if (!record(value)) throw new Error(`Expected an object for ${context}`);
  for (const key of Object.keys(value)) if (!allowed.includes(key)) throw new Error(`Unknown ${context} option: ${key}`);
}
function nonempty(value, context) {
  if (typeof value !== 'string' || !value.trim()) throw new Error(`${context} must be a nonempty string`);
  return value;
}

/** Export feature dictionaries to Android's R.string resources, independently of Metro/React. */
async function generateAndroidResources(options) {
  fields(options, ['$schema', 'projectRoot', 'root', 'defaultLanguage', 'languages', 'locales', 'resources'], 'Android resources');
  const projectRoot = resolveRoot(process.cwd(), options.projectRoot);
  const root = resolveRoot(projectRoot, options.root);
  const defaultLanguage = nonempty(options.defaultLanguage, 'defaultLanguage');
  if (!Array.isArray(options.resources) || !options.resources.length) throw new Error('resources must be a nonempty list');
  if (options.locales !== undefined && !record(options.locales)) throw new Error('locales must be an object');
  const dictionaries = new Map();
  const targets = [];
  const foundLanguages = new Set();
  const targetPaths = new Set();
  for (const target of options.resources) {
    fields(target, ['outputDir', 'fileName', 'dictionaries', 'strings'], 'resource target');
    const outputDir = path.resolve(root, nonempty(target.outputDir, 'outputDir'));
    const fileName = target.fileName ?? 'i18n_json_react.xml';
    if (typeof fileName !== 'string' || !/^[a-z][a-z0-9_]*\.xml$/.test(fileName)) throw new Error(`Invalid Android resource fileName: ${fileName}`);
    const targetPath = path.join(outputDir, fileName);
    if (targetPaths.has(targetPath)) throw new Error(`Duplicate Android resource target: ${targetPath}`);
    targetPaths.add(targetPath);
    if (!Array.isArray(target.dictionaries) || !target.dictionaries.length) throw new Error('dictionaries must be a nonempty list');
    const chain = [];
    for (const input of target.dictionaries) {
      const file = path.resolve(root, nonempty(input, 'dictionary path'));
      if (!dictionaries.has(file)) dictionaries.set(file, parseFeature(await readFile(file, 'utf8'), file));
      const dictionary = dictionaries.get(file);
      Object.keys(dictionary).forEach(language => foundLanguages.add(language));
      chain.push(dictionary);
    }
    if (!record(target.strings) || !Object.keys(target.strings).length) throw new Error('strings must be a nonempty resource-name to message-key object');
    const strings = Object.entries(target.strings).map(([name, binding]) => {
      if (!RESOURCE_NAME.test(name)) throw new Error(`Invalid Android resource name: ${name}`);
      if (typeof binding === 'string') return {name, key: binding};
      fields(binding, ['key', 'formatted'], `resource ${name}`);
      if (typeof binding.key !== 'string') throw new Error(`Expected a message key for resource ${name}`);
      if (binding.formatted !== undefined && typeof binding.formatted !== 'boolean') throw new Error(`formatted must be a boolean for resource ${name}`);
      return {name, ...binding};
    });
    targets.push({outputDir, fileName, chain, strings});
  }
  const languages = options.languages ?? [...foundLanguages].sort();
  if (!Array.isArray(languages) || !languages.length || languages.some(language => typeof language !== 'string') || new Set(languages).size !== languages.length)
    throw new Error('languages must be a nonempty list without duplicates');
  if (!languages.includes(defaultLanguage)) throw new Error('languages must include defaultLanguage');
  for (const language of languages) if (!foundLanguages.has(language)) throw new Error(`No translations found for language: ${language}`);
  for (const language of Object.keys(options.locales ?? {})) if (!languages.includes(language)) throw new Error(`Locale mapping for unselected language: ${language}`);
  const directories = new Map();
  const qualifiers = new Set();
  for (const language of languages) {
    const qualifier = localeDirectory(options.locales?.[language] ?? language);
    if (qualifiers.has(qualifier)) throw new Error(`Languages resolve to the same Android locale: ${language}`);
    qualifiers.add(qualifier);
    directories.set(language, language === defaultLanguage ? 'values' : qualifier);
  }
  // Validate every translation and destination before writing any resources.
  const writes = [], stale = new Set();
  for (const target of targets) {
    const rendered = new Map(languages.map(language => [language, []]));
    for (const binding of target.strings) {
      const baseline = lookup(target.chain, defaultLanguage, binding.key);
      if (baseline === undefined) throw new Error(`Missing ${defaultLanguage} translation for Android resource ${binding.name}: ${binding.key}`);
      const texts = languages.map(language => lookup(target.chain, language, binding.key) ?? baseline);
      const formatted = binding.formatted ?? texts.some(text => /%[1-9]\d*\$/.test(text));
      const signature = formatted ? formatSignature(baseline, binding.name) : undefined;
      for (const [index, language] of languages.entries()) {
        const value = texts[index];
        if (formatted && JSON.stringify(formatSignature(value, binding.name)) !== JSON.stringify(signature))
          throw new Error(`Formatting arguments differ in ${language} for Android resource ${binding.name}`);
        rendered.get(language).push(`    <string name="${binding.name}" formatted="${formatted}">"${escapeAndroidText(value)}"</string>`);
      }
    }
    const expected = new Set();
    for (const [language, lines] of rendered) {
      const file = path.join(target.outputDir, directories.get(language), target.fileName);
      expected.add(file);
      const previous = await existingResource(file);
      if (previous !== undefined && !previous.startsWith(HEADER)) throw new Error(`Refusing to overwrite a non-generated Android resource file: ${file}`);
      writes.push({file, content: `${HEADER}<resources>\n${lines.join('\n')}\n</resources>\n`, previous});
    }
    let entries;
    try {entries = await readdir(target.outputDir, {withFileTypes: true});} catch (error) {if (error.code !== 'ENOENT') throw error; entries = [];}
    for (const entry of entries) {
      if (!entry.isDirectory() || !/^values(?:-[a-zA-Z0-9+_-]+)?$/.test(entry.name)) continue;
      const file = path.join(target.outputDir, entry.name, target.fileName);
      if (!expected.has(file) && (await existingResource(file))?.startsWith(HEADER)) stale.add(file);
    }
  }
  const files = writes.map(write => write.file);
  if (new Set(files).size !== files.length) throw new Error('Overlapping Android resource output paths');
  for (const {file, content, previous} of writes) if (content !== previous) await writeChanged(file, content);
  for (const file of stale) await unlink(file);
  return {root, languages: [...languages], files};
}

async function generateAndroidResourcesFromConfig(configFile, options = {}) {
  const file = path.resolve(options.projectRoot ?? process.cwd(), nonempty(configFile, 'config file'));
  const config = JSON.parse(await readFile(file, 'utf8'));
  if (!record(config) || own(config, 'projectRoot')) throw new Error('Resource config must be an object without projectRoot');
  return generateAndroidResources({...config, projectRoot: path.dirname(file)});
}

function lookup(chain, language, key) {
  for (const dictionary of chain) if (dictionary[language] && own(dictionary[language], key)) return dictionary[language][key];
}
function localeDirectory(tag) {
  let locale;
  try {locale = new Intl.Locale(nonempty(tag, 'locale').replaceAll('_', '-'));} catch {throw new Error(`Invalid Android locale: ${tag}`);}
  if (!/^[a-z]{2,3}$/.test(locale.language)) throw new Error(`Map the dictionary identifier to an Android language tag using locales: ${tag}`);
  if (locale.toString() !== locale.baseName) throw new Error(`Android resource locales must not contain extensions: ${tag}`);
  return /^[a-z]{2,3}$/.test(locale.baseName) ? `values-${locale.baseName}` : `values-b+${locale.baseName.replaceAll('-', '+')}`;
}
function escapeAndroidText(text) {
  // Android applies its own escaping after XML decoding; quotes preserve whitespace.
  if (/[^\u0009\u000a\u000d\u0020-\ud7ff\ue000-\ufffd\u{10000}-\u{10ffff}]/u.test(text)) throw new Error('Android resource text contains an invalid XML character');
  let escaped = text.replaceAll('\\', '\\\\').replaceAll('"', '\\"').replaceAll("'", "\\'")
    .replaceAll('\n', '\\n').replaceAll('\t', '\\t').replaceAll('\r', '\\u000D');
  if (/^[@?]/.test(escaped)) escaped = `\\${escaped}`;
  return escaped.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
}
function formatSignature(text, name) {
  const argumentsByIndex = new Map();
  for (let position = 0; position < text.length; position++) {
    if (text[position] !== '%') continue;
    if (text[position + 1] === '%' || text[position + 1] === 'n') {position++; continue;}
    const match = /^%([1-9]\d*)\$[-#+ 0,(]*\d*(?:\.\d+)?([tT][HIklMSLNpzZsQBbhAaCYyjmdeRTrDFc]|[bBhHsScCdoxXeEfgGaA])/.exec(text.slice(position));
    if (!match) throw new Error(`Use valid positional format arguments such as %1$s in Android resource ${name}`);
    const conversion = match[2];
    const type = conversion.length === 2 ? 'date' : /[doxX]/.test(conversion) ? 'integer' : /[eEfgGaA]/.test(conversion) ? 'number' : conversion.toLowerCase();
    const index = Number(match[1]);
    if (!Number.isSafeInteger(index) || index > 2147483647) throw new Error(`Invalid format argument index in Android resource ${name}`);
    const types = argumentsByIndex.get(index) ?? new Set(); types.add(type); argumentsByIndex.set(index, types);
    position += match[0].length - 1;
  }
  return [...argumentsByIndex].sort(([a], [b]) => a - b).map(([index, types]) => [index, [...types].sort()]);
}
async function existingResource(file) {
  let stats;
  try {stats = await lstat(file);} catch (error) {if (error.code === 'ENOENT') return; throw error;}
  if (!stats.isFile() || stats.isSymbolicLink()) throw new Error(`Refusing to modify a non-file Android resource: ${file}`);
  return readFile(file, 'utf8');
}
async function writeChanged(file, content) {
  await mkdir(path.dirname(file), {recursive: true});
  const temporary = `${file}.${randomUUID()}.tmp`;
  try {await writeFile(temporary, content); await rename(temporary, file);} catch (error) {
    try {await unlink(temporary);} catch (cleanup) {if (cleanup.code !== 'ENOENT') console.error(cleanup);}
    throw error;
  }
}

module.exports = {generateAndroidResources, generateAndroidResourcesFromConfig};
