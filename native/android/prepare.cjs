const { mkdir, readFile, readdir, rename, unlink, writeFile } = require('node:fs/promises');
const { randomUUID } = require('node:crypto');
const path = require('node:path');
const { collectDictionaries, computeId, resolveRoot } = require('../../bundlers/shared.cjs');

const ASSET_EXTENSION = 'i18npack';
const MARKER = '.generated-by-i18n-json-react';

/** Produces data assets and tiny reference modules, without moving feature-local source JSON. */
async function prepareAndroidI18n(options = {}) {
  const projectRoot = resolveRoot(process.cwd(), options.projectRoot);
  const root = resolveRoot(projectRoot, options.root);
  const outputDir = path.resolve(projectRoot, options.outputDir ?? '.i18n-json-react');
  if (outputDir === root || outputDir === projectRoot)
    throw new Error('outputDir must be a dedicated generated directory');
  const relativeOutput = path.relative(root, outputDir).split(path.sep).join('/');
  const directories = new Set([root, outputDir]);
  const { files, perLanguage, fingerprints } = await collectDictionaries(
    root,
    {
      dirs: options.dirs ?? ['.'],
      exclude: [...(options.exclude ?? []), ...(!relativeOutput.startsWith('..') ? [`${relativeOutput}/**`] : [])],
    },
    directory => directories.add(directory),
  );
  const languages = options.languages ?? [...perLanguage.keys()].sort();
  if (options.languages && (!languages.length || new Set(languages).size !== languages.length)) {
    throw new Error('languages must be a nonempty list without duplicates');
  }
  for (const language of languages) {
    if (!perLanguage.has(language)) throw new Error(`No translations found for language: ${language}`);
  }

  await prepareOutput(outputDir);
  const assetDir = path.join(outputDir, 'assets');
  const referenceDir = path.join(outputDir, 'references');
  await mkdir(assetDir, { recursive: true });
  await mkdir(referenceDir, { recursive: true });
  const assets = [];
  for (const language of languages) {
    const file = `${language}.${ASSET_EXTENSION}`;
    await writeChanged(path.join(assetDir, file), JSON.stringify(perLanguage.get(language)));
    assets.push(file);
  }
  const references = new Map();
  for (const file of files) {
    const id = computeId(file, root);
    const target = path.join(referenceDir, `${id}.js`);
    await writeChanged(target, `module.exports = ${JSON.stringify({ __id: id })};\n`);
    references.set(file, target);
  }
  await removeStale(assetDir, new Set(assets), /^[A-Za-z0-9_-]+\.i18npack$/);
  await removeStale(
    referenceDir,
    new Set([...references.values()].map(file => path.basename(file))),
    /^[a-f0-9]{16}\.js$/,
  );
  const providers = languages.map(
    language =>
      `  ${JSON.stringify(language)}: () => require(${JSON.stringify(`./assets/${language}.${ASSET_EXTENSION}`)})`,
  );
  const manifestPath = path.join(outputDir, 'manifest.cjs');
  await writeChanged(
    manifestPath,
    `// Generated. Each language asset is required only when selected.\nmodule.exports = Object.freeze({\n${providers.join(',\n')}\n});\n`,
  );
  const fields = languages.map(language => `  readonly ${JSON.stringify(language)}: () => number;`);
  await writeChanged(
    path.join(outputDir, 'manifest.d.cts'),
    `declare const assets: {\n${fields.join('\n')}\n};\nexport = assets;\n`,
  );
  return {
    root,
    outputDir,
    manifestPath,
    languages: [...languages],
    references,
    fingerprints,
    watchFolders: [...directories],
  };
}

async function prepareOutput(outputDir) {
  await mkdir(outputDir, { recursive: true });
  const contents = await readdir(outputDir);
  if (contents.length && !contents.includes(MARKER)) {
    throw new Error(`Refusing to overwrite a non-generated directory: ${outputDir}`);
  }
  await writeChanged(path.join(outputDir, MARKER), 'Generated by i18n-json-react.\n');
}

async function writeChanged(file, content) {
  let previous;
  try {
    previous = await readFile(file, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (previous === content) return;
  const temporary = `${file}.${randomUUID()}.tmp`;
  try {
    await writeFile(temporary, content);
    await rename(temporary, file);
  } catch (error) {
    try {
      await unlink(temporary);
    } catch (cleanupError) {
      if (cleanupError.code !== 'ENOENT') console.error(cleanupError);
    }
    throw error;
  }
}

async function removeStale(directory, keep, pattern) {
  for (const file of await readdir(directory)) {
    if (pattern.test(file) && !keep.has(file)) await unlink(path.join(directory, file));
  }
}

module.exports = { prepareAndroidI18n, ASSET_EXTENSION };
